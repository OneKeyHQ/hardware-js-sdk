const fs = require('fs');
const path = require('path');
const protobuf = require('protobufjs/light');
const Long = require('long');

protobuf.util.Long = Long;
protobuf.configure();

const packageRoot = path.resolve(__dirname, '..');
const outputDirectory = path.join(packageRoot, 'src/serialization/protobuf/generated');
const schemaPaths = [
  '../core/src/data/messages/messages.json',
  '../core/src/data/messages/messages_legacy_v1.json',
  'messages-protocol-v2.json',
  'src/serialization/protobuf/legacy-protocol-info.json',
];
const methods = ['encode', 'decode', 'verify', 'fromObject', 'toObject'];
const factories = new Map();
const registrations = [];

function collectTypes(namespace) {
  return [
    ...(namespace instanceof protobuf.Type ? [namespace] : []),
    ...(namespace.nestedArray || []).flatMap(collectTypes),
  ];
}

for (const schemaPath of schemaPaths) {
  const schema = JSON.parse(fs.readFileSync(path.join(packageRoot, schemaPath), 'utf8'));
  const root = protobuf.Root.fromJSON(schema);
  // Capture before resolution, which can normalize field options in place.
  const signature = JSON.stringify(root.toJSON());
  const registrationsForSchema = [];
  for (const type of collectTypes(root)) {
    type.setup();
    const source = [
      `type.ctor = ${type.ctor.toString()};`,
      'const types = type.fieldsArray.map(field => field.resolvedType);',
      ...methods.map(method => `type.${method} = ${type[method].toString()};`),
    ].join('\n');
    if (!factories.has(source)) factories.set(source, factories.size);
    registrationsForSchema.push([type.fullName, factories.get(source)]);
  }
  registrations.push({ signature, types: registrationsForSchema });
}

// Keep the exact generated algorithms, including legacy conversion quirks.
const source = [
  '// @generated by scripts/protobuf-static.js. DO NOT EDIT.',
  `const { Reader, Writer, util } = require('protobufjs/minimal');`,
  'const factories = [',
  ...Array.from(factories.keys(), body => `function(type) {\n${body}\n},`),
  '];',
  `const schemas = ${JSON.stringify(registrations)};`,
  'exports.installStaticCodecs = function(root) {',
  '  const signature = JSON.stringify(root.toJSON());',
  '  const schema = schemas.find(candidate => candidate.signature === signature);',
  '  if (!schema) return false;',
  '  for (const [name, factory] of schema.types) factories[factory](root.lookupType(name));',
  '  return true;',
  '};',
  '',
].join('\n');
const declaration = [
  '// @generated by scripts/protobuf-static.js. DO NOT EDIT.',
  "import type { Root } from 'protobufjs/light';",
  'export declare function installStaticCodecs(root: Root): boolean;',
  '',
].join('\n');

for (const [name, content] of [
  ['codecs.js', source],
  ['codecs.d.ts', declaration],
]) {
  const destination = path.join(outputDirectory, name);
  if (process.argv.includes('--check')) {
    if (!fs.existsSync(destination) || fs.readFileSync(destination, 'utf8') !== content) {
      throw new Error(`Static protobuf is stale: run yarn update-protobuf:static (${name})`);
    }
  } else {
    fs.mkdirSync(outputDirectory, { recursive: true });
    fs.writeFileSync(destination, content);
  }
}
console.log(`Static protobuf: ${registrations.length} schemas, ${factories.size} shared codecs`);

const fs = require('fs');
const path = require('path');
const protobuf = require('protobufjs/light');
const pbjs = require('protobufjs/cli/pbjs');

const packageRoot = path.resolve(__dirname, '..');
const outputDirectory = path.join(packageRoot, 'lib');
const legacyProtocolInfoSchema = {
  nested: {
    LegacyProtocolInfo: {
      fields: {
        version: { rule: 'required', type: 'uint32', id: 1 },
        supported_messages: {
          rule: 'repeated',
          type: 'uint32',
          id: 2,
          options: { packed: false },
        },
        protobuf_definition: { type: 'string', id: 3 },
      },
    },
  },
};

// Match descriptors independent of JSON property order, without a hash collision risk.
function schemaKey(schema) {
  return JSON.stringify(schema, (_key, value) => {
    if (value && typeof value === 'object' && !Array.isArray(value)) {
      return Object.keys(value)
        .sort()
        .reduce((result, key) => {
          result[key] = value[key];
          return result;
        }, {});
    }
    return value;
  });
}

async function generate() {
  fs.mkdirSync(outputDirectory, { recursive: true });
  const legacyPath = path.join(outputDirectory, 'legacy-protocol-info.json');
  fs.writeFileSync(legacyPath, JSON.stringify(legacyProtocolInfoSchema));
  const sources = [
    path.resolve(packageRoot, '../core/src/data/messages/messages.json'),
    path.resolve(packageRoot, '../core/src/data/messages/messages_legacy_v1.json'),
    path.join(packageRoot, 'messages-protocol-v2.json'),
    legacyPath,
  ];
  const entries = [];
  for (const [index, source] of sources.entries()) {
    const schema = JSON.parse(fs.readFileSync(source, 'utf8'));
    const code = await new Promise((resolve, reject) => {
      pbjs.main(
        ['-t', 'static', '--no-comments', '--no-service', '--root', `onekey-csp-${index}`, source],
        (error, output) => (error ? reject(error) : resolve(output))
      );
    });
    const types = [];
    const collect = namespace => {
      if (namespace instanceof protobuf.Type) {
        const reference = namespace.fullName
          .split('.')
          .slice(1)
          .map(name => `[${JSON.stringify(name)}]`)
          .join('');
        types.push(`${JSON.stringify(namespace.fullName)}: $root${reference}`);
      }
      (namespace.nestedArray || []).forEach(collect);
    };
    collect(protobuf.Root.fromJSON(schema));
    entries.push(
      `${JSON.stringify(
        schemaKey(schema)
      )}: function () {\nconst $protobuf = { ...protobuf, roots: {} };\n${code}\nreturn {${types.join(
        ',\n'
      )}};\n}`
    );
  }
  fs.writeFileSync(
    path.join(outputDirectory, 'protobuf-static.js'),
    `// Generated by scripts/protobuf-static.js. Do not edit.\n` +
      `/* istanbul ignore file */\n` +
      `const protobuf = require('protobufjs/minimal');\n` +
      `protobuf.util.Long = require('long');\nprotobuf.configure();\n` +
      `${schemaKey.toString()}\n` +
      `module.exports = { schemaKey, legacyProtocolInfoSchema: ${JSON.stringify(
        legacyProtocolInfoSchema
      )}, schemas: {\n${entries.join(',\n')}\n} };\n`
  );
  fs.writeFileSync(
    path.join(outputDirectory, 'protobuf-static.d.ts'),
    `import type { Constructor, INamespace, Type } from 'protobufjs/light';\n` +
      `type StaticMessageConstructor = Constructor<{}> & Pick<Type, 'encode' | 'decode' | 'verify' | 'fromObject' | 'toObject'>;\n` +
      `export function schemaKey(schema: INamespace): string;\n` +
      `export const schemas: Partial<Record<string, () => Record<string, StaticMessageConstructor>>>;\n` +
      `export const legacyProtocolInfoSchema: INamespace;\n`
  );
  fs.unlinkSync(legacyPath);
}

generate().catch(error => {
  console.error(error);
  process.exitCode = 1;
});
